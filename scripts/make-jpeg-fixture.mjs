// Regenerates src/db/jpegFixture.ts: one real, decodable baseline JPEG that the
// seeder then pads to whatever size a plan asks for. It needs a JPEG encoder,
// which the app itself never does, so install it, run this, and drop it again:
//
//   npm i --no-save jpeg-js && node scripts/make-jpeg-fixture.mjs && npm rm jpeg-js
//
// The padding is JPEG comment (COM, 0xFFFE) segments placed between SOI and the
// first marker segment, which is where the spec says marker segments belong: a
// decoder reads them and skips them, so the bytes stay a photograph at any size.
import { encode, decode } from 'jpeg-js'
import { writeFileSync } from 'node:fs'

const W = 160
const H = 120
const Q = 78
const MAX_SEGMENT = 65533

/** A small image with real detail: a gradient, a diagonal band and some noise. */
function image() {
  const data = new Uint8ClampedArray(W * H * 4)
  let n = 0x9e3779b9 >>> 0
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      // Deterministic xorshift, so re-running this script does not change the file.
      n ^= n << 13
      n >>>= 0
      n ^= n >>> 17
      n ^= n << 5
      n >>>= 0
      const noise = (n % 255) / 255
      const band = Math.sin((x + y * 1.7) / 9) * 0.5 + 0.5
      const i = (y * W + x) * 4
      data[i] = 40 + (x / W) * 190 + band * 40
      data[i + 1] = 60 + (y / H) * 150 + noise * 26
      data[i + 2] = 90 + band * 120 + noise * 18
      data[i + 3] = 255
    }
  }
  return { data, width: W, height: H }
}

const raw = encode(image(), Q).data
if (raw[0] !== 0xff || raw[1] !== 0xd8) throw new Error('encoder did not produce a JPEG')
const before = decode(raw)

/**
 * The same arithmetic the runtime module does, kept here so the generator can
 * prove the padded file still decodes to the same picture.
 */
function padded(bytes, seed) {
  let left = bytes - 2 - (raw.length - 2)
  if (left < 4) throw new Error(`${bytes} bytes is smaller than the baseline image`)
  const parts = [raw.subarray(0, 2)]
  let k = seed >>> 0
  while (left >= 4) {
    const len = Math.min(MAX_SEGMENT, left - 4)
    const seg = new Uint8Array(4 + len)
    seg[0] = 0xff
    seg[1] = 0xfe
    seg[2] = (len + 2) >> 8
    seg[3] = (len + 2) & 0xff
    for (let i = 0; i < len; i++) {
      k ^= k << 13
      k >>>= 0
      k ^= k >>> 17
      k ^= k << 5
      k >>>= 0
      seg[4 + i] = 32 + (k % 95)
    }
    parts.push(seg)
    left -= 4 + len
  }
  if (left !== 0) throw new Error('comment segments did not add up')
  parts.push(raw.subarray(2))
  const out = new Uint8Array(parts.reduce((n, p) => n + p.length, 0))
  let at = 0
  for (const p of parts) {
    out.set(p, at)
    at += p.length
  }
  return out
}

// ---- Checks: the padded file has to stay a real photograph at any size.
const sizes = [raw.length + 4, raw.length + 500, 8_000, 40_000, 150_000, 300_000]
for (const size of sizes) {
  const bytes = padded(size, 7)
  if (bytes.length !== size) throw new Error(`asked for ${size}, built ${bytes.length}`)
  if (bytes[0] !== 0xff || bytes[1] !== 0xd8) throw new Error('lost the SOI marker')
  if (bytes[bytes.length - 2] !== 0xff || bytes[bytes.length - 1] !== 0xd9) throw new Error('lost the EOI marker')
  const after = decode(bytes)
  if (after.width !== before.width || after.height !== before.height) throw new Error('padded JPEG changed shape')
  for (const at of [0, 1_000, before.data.length - 4]) {
    if (after.data[at] !== before.data[at]) throw new Error(`padded JPEG decodes differently at ${at}`)
  }
}
const one = padded(40_000, 1)
const two = padded(40_000, 2)
if (one.every((v, i) => v === two[i])) throw new Error('two seeds produced identical bytes')

const b64 = Buffer.from(raw).toString('base64')
const chunks = b64.match(/.{1,96}/g).map((c) => `  '${c}'`).join(' +\n')

const module = `/**
 * One real photograph, checked in as base64.
 *
 * Generated by scripts/make-jpeg-fixture.mjs, which also proves that the padded
 * forms below still decode to this picture. The seeder needs bytes a phone will
 * treat as a JPEG - the storage estimate, the photo decoders and the export code
 * all care - and it needs them at an exact size so that \`Photo.bytes\` can be the
 * sum of what is really stored rather than a number someone hoped for.
 *
 * Do not edit the string by hand: regenerate it.
 */
const BASE_JPEG_BASE64 =
${chunks}

/** SOI, then every marker segment, the scan data and EOI. */
const base = Uint8Array.from(atob(BASE_JPEG_BASE64), (c) => c.charCodeAt(0))
const HEAD = base.subarray(0, 2)
const TAIL = base.subarray(2)

/** What the photograph really measures, so a seeded \`Photo\` can say the same. */
export const JPEG_WIDTH_PX = ${W}
export const JPEG_HEIGHT_PX = ${H}

/** A JPEG comment segment's length field is 16 bits and counts itself. */
const MAX_SEGMENT = 65533

/** The smallest size \`jpegAtSize\` can build: the photo plus one comment segment. */
export const JPEG_MIN_BYTES: number = HEAD.length + TAIL.length + 4

/**
 * The photograph, padded with JPEG comment segments to exactly \`bytes\`.
 *
 * The payload comes from \`seed\`, so two photos of the same size are not the same
 * bytes. A seeder that wrote one identical blob 15,000 times would let whatever
 * deduplication or compression the layer below does flatter the storage estimate.
 *
 * The return type spells out \`ArrayBuffer\`: the default \`ArrayBufferLike\` also
 * admits \`SharedArrayBuffer\`, which is not a \`BlobPart\`, so the seeder's
 * \`new Blob(jpegAtSize(...))\` would not compile.
 */
export function jpegAtSize(bytes: number, seed: number): Uint8Array<ArrayBuffer> {
  let left = bytes - HEAD.length - TAIL.length
  if (left < 4) throw new Error(\`cannot pad a JPEG to \${bytes} bytes: the photo itself needs \${JPEG_MIN_BYTES}\`)
  const parts: Uint8Array[] = [HEAD]
  let k = seed >>> 0
  while (left >= 4) {
    const len = Math.min(MAX_SEGMENT, left - 4)
    const segment = new Uint8Array(4 + len)
    segment[0] = 0xff
    segment[1] = 0xfe
    segment[2] = (len + 2) >> 8
    segment[3] = (len + 2) & 0xff
    for (let i = 0; i < len; i++) {
      // xorshift32: cheap, deterministic, and enough to make each photo its own bytes.
      k ^= k << 13
      k >>>= 0
      k ^= k >>> 17
      k ^= k << 5
      k >>>= 0
      segment[4 + i] = 32 + (k % 95)
    }
    parts.push(segment)
    left -= 4 + len
  }
  if (left !== 0) throw new Error('comment segments did not add up')
  parts.push(TAIL)
  const out = new Uint8Array(parts.reduce((n, p) => n + p.length, 0))
  let at = 0
  for (const part of parts) {
    out.set(part, at)
    at += part.length
  }
  return out
}
`

writeFileSync('src/db/jpegFixture.ts', module)
console.log(`baseline JPEG: ${raw.length} bytes (${before.width}x${before.height}), smallest padded: ${raw.length + 4}`)
